"""Load the v2 (question-independent) firmware into the 25-bank ROM boundary.

The v2 SoC build differs from the original only in its ROM contents (and the
ROM array length LiteX derives from them); this is checked on the generated
RTL before the swap.  Only the 25 bank modules' contents change; the RTL,
macro mapping, latency and every other memory initialization are identical.
The new boundary's lineage is bound to the v2 CPU execution so the complete
replay is compared against the v2 reference transcript.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.student_mini import sha
from scripts.retry_student_mini_route import verify
from scripts.prepare_student_mini_cpu_rom_banks import bank_module, TOP, BLOCK, BANKS, WORDS

ROM_LINES = re.compile(r'^(// Memory rom: \d+-words x 32-bit|reg \[31:0\] rom\[0:\d+\];|// Date       : [0-9: -]+|//  Auto-Generated by LiteX on [0-9: -]+\.)$', re.M)


def checked_runs(old, new):
    for run in (old, new):
        value = json.loads((run / 'completion.json').read_text())
        if value.get('target_run_complete') is not True:
            raise ValueError(f'{run} is not a complete CPU execution')
        for name, digest in value['artifacts'].items():
            if sha(run / name) != digest:
                raise ValueError(f'{run}/{name} changed')
    old_rtl = (old / 'soc/gateware/sim.v').read_text()
    new_rtl = (new / 'soc/gateware/sim.v').read_text()
    strip = lambda text: ROM_LINES.sub('ROM-LENGTH', text)
    if strip(old_rtl) != strip(new_rtl):
        raise ValueError('v2 SoC RTL differs beyond the ROM length')
    for name in ('sim_mem.init', 'sim_mem_1.init', 'sim_mem_2.init', 'sim_mem_3.init', 'sim_mem_4.init', 'sim_sram.init'):
        if (old / 'soc/gateware' / name).read_bytes() != (new / 'soc/gateware' / name).read_bytes():
            raise ValueError('non-ROM memory initialization differs: ' + name)
    csr = lambda run: [l for l in (run / 'soc/csr.csv').read_text().splitlines() if not l.startswith('#')]
    if csr(old) != csr(new):
        raise ValueError('CSR map differs')
    words = [int(line, 16) for line in (new / 'soc/gateware/sim_rom.init').read_text().split()]
    if not words or len(words) > BANKS * WORDS:
        raise ValueError(f'v2 ROM of {len(words)} words does not fit {BANKS} banks')
    return words


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mapping', type=Path, required=True, help='replay-qualified 25-bank ROM boundary')
    parser.add_argument('--old-cpu-run', type=Path, required=True)
    parser.add_argument('--new-cpu-run', type=Path, required=True)
    args = parser.parse_args()
    mapping, old, new = args.mapping.resolve(), args.old_cpu_run.resolve(), args.new_cpu_run.resolve()
    parent = json.loads((mapping / 'completion.json').read_text())
    if parent['status'] != 'CPU_ROM_BANKS_MAPPING_STAGE_PASS' or parent.get('rom_banks') != BANKS:
        raise ValueError('25-bank ROM boundary required')
    verify(parent['bindings'])
    if parent['bindings'].get(str(old / 'completion.json')) != sha(old / 'completion.json'):
        raise ValueError('boundary does not descend from the old CPU execution')
    words = checked_runs(old, new)
    text = (mapping / 'mapped.v').read_text()
    for index in range(BANKS):
        name = f'student_mini_cpu_rom_bank_{index:02d}'
        match = re.search(r'// Firmware ROM bank ' + str(index) + r':.*?\nmodule ' + name + r' \(.*?\nendmodule\n', text, re.S)
        if not match:
            raise ValueError('bank module missing: ' + name)
        bank = [words[index * WORDS + i] if index * WORDS + i < len(words) else 0 for i in range(WORDS)]
        text = text.replace(match.group(0), bank_module(index, bank), 1)
    paths = [Path(__file__), ROOT / 'scripts/prepare_student_mini_cpu_rom_banks.py', mapping / 'completion.json',
             mapping / 'mapped.v', old / 'completion.json', new / 'completion.json', new / 'soc/gateware/sim_rom.init',
             new / 'soc/gateware/sim.v', old / 'soc/gateware/sim.v']
    bindings = {str(p): sha(p) for p in paths}
    bindings.update(parent['bindings'])
    key = hashlib.sha256(json.dumps(bindings, sort_keys=True).encode()).hexdigest()
    work = ROOT / 'build/student-mini/cpu-rom-v2-boundary' / key
    (work / 'banks').mkdir(parents=True, exist_ok=False)
    (work / 'mapped.v').write_text(text)
    for index in range(BANKS):
        bank = [words[index * WORDS + i] if index * WORDS + i < len(words) else 0 for i in range(WORDS)]
        (work / 'banks' / f'student_mini_cpu_rom_bank_{index:02d}.v').write_text(bank_module(index, bank))
    yosys = Path('/home/soclab/tools/oss-cad-suite/bin/yosys')
    macro = ROOT / 'build/openram/vortex-banked/vortex_sp_32x1024_w4/vortex_sp_32x1024_w4.v'
    script = work / 'structure.ys'
    script.write_text(f'read_verilog -sv {work / "mapped.v"}\nread_verilog -lib {macro}\n'
                      f'hierarchy -check -top {TOP}\nproc\nwrite_json {work / "mapped.json"}\nstat\n')
    with (work / 'yosys.log').open('x') as log:
        if subprocess.call([str(yosys), '-q', '-s', str(script)], stdout=log, stderr=subprocess.STDOUT):
            raise RuntimeError('v2 ROM boundary does not elaborate')
    # Everything outside the 25 bank modules (top, ROM wrapper, all other
    # modules) must be byte-identical to the replay-qualified parent.
    banks = re.compile(r'// Firmware ROM bank \d+:.*?\nmodule student_mini_cpu_rom_bank_\d+ \(.*?\nendmodule\n', re.S)
    if banks.sub('', text) != banks.sub('', (mapping / 'mapped.v').read_text()):
        raise ValueError('netlist changed beyond ROM bank contents')
    verify(bindings)
    result = dict(parent, status='CPU_ROM_BANKS_MAPPING_STAGE_PASS', bindings=bindings, parent_mapping=str(mapping),
                  firmware='combined_mini_bios_v2', rom_words=len(words), parent_cpu_run=str(new),
                  reason='v2 firmware loaded into the 25 ROM banks; RTL and mapping unchanged; complete replay still required')
    result.pop('elapsed_seconds', None)
    result['artifacts'] = {p.relative_to(work).as_posix(): sha(p) for p in work.rglob('*') if p.is_file()}
    (work / 'completion.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(work=str(work), status=result['status'], rom_words=len(words))))


if __name__ == '__main__':
    main()
